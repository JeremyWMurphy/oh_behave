function [csd, src_grid] = compute_icsd_2d(lfp, x_coords, y_coords, R, sigma, lambda)
% COMPUTE_ICSD_2D Computes 2D regularized iCSD for Neuropixels 2.0
%
% Inputs:
%   lfp      - Matrix of LFP data (Channels x Time), e.g., [384 x 2001]
%   x_coords - Vector of horizontal channel coordinates in meters (0 or 32e-6)
%   y_coords - Vector of vertical channel depths in meters (0 to N*15e-6)
%   R        - Radius of the source disc in meters (e.g., 25e-6)
%   sigma    - Extracellular conductivity in S/m (0.3)
%   lambda   - Regularization parameter to stop noise explosion (e.g., 0.01)

num_channels = size(lfp, 1);
src_grid = [x_coords(:), y_coords(:)];

% Initialize the true 2D forward matrix
F = zeros(num_channels, num_channels);

% Calculate the electrostatic potential field generated by 2D cylinder discs
for i = 1:num_channels
    for j = 1:num_channels
        % True Euclidean distance between channel i and channel j
        r = sqrt((src_grid(i,1) - src_grid(j,1))^2 + (src_grid(i,2) - src_grid(j,2))^2);

        % Electrostatic disc interaction formula (handles x and y spacing cleanly)
        if r == 0
            F(i,j) = (R / sigma); % Self-interaction ceiling
        else
            F(i,j) = (R^2) / (4 * sigma * r);
        end
    end
end

% Invert the matrix safely using Ridge Regression (Tikhonov Regularization)
% This step completely suppresses the messy matrix explosions.
F_inv = (F' * F + lambda * eye(num_channels)) \ F';
csd = F_inv * lfp;
end
